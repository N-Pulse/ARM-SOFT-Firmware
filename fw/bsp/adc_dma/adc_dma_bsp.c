// ─── ADC / current sensing (TO FILL IN) ──────────────────────────────────────
//
// The STM32G474 has 5 ADCs (ADC1–ADC5). Recommended setup for 8 shunts:
//   ADC1  channels 1–5  → MOTOR_THUMB … MOTOR_LITTLE   (PA0–PA4 or similar)
//   ADC2  channels 1–3  → MOTOR_WRIST_X … MOTOR_PALM
//
// Steps in STM32CubeIDE:
//   1. Open .ioc → Analog → ADC1 → enable scan mode, DMA continuous.
//   2. Add DMA1 Channel 1 → ADC1 in circular mode, half-word, no increment src.
//   3. Enable ADC1 global interrupt (for DMA half/full complete).
//   4. Repeat for ADC2 if needed.
//   5. Set sampling time ≥ 12.5 cycles to allow the RC filter to settle.
//   6. Update SHUNT_OHMS to match the PCB value.
//   7. In HAL_ADC_ConvCpltCallback: convert raw counts to mN and call
//      MotorBackend_OnFeedback() for each motor.
// ─────────────────────────────────────────────────────────────────────────────

#define SHUNT_OHMS     0.01f   // TODO: update to actual shunt resistance
#define ADC_VREF_MV    3300U
#define ADC_FULL_SCALE 4095U   // 12-bit

