uint16_t ADC_DMA_BSP_GetRaw(motor_id_t id)
{
    if ((uint32_t)id >= MOTOR_COUNT) return 0U;
    return s_adc_raw[id];
}

float ADC_DMA_BSP_GetCurrentA(motor_id_t id)
{
    float voltage_v = ((float)ADC_DMA_BSP_GetRaw(id) / (float)ADC_FULL_SCALE)
                      * ((float)ADC_VREF_MV / 1000.0f);
    return voltage_v / SHUNT_OHMS;
}

